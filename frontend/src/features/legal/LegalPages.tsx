import { useQuery } from '@tanstack/react-query'
import { useEffect, type ReactNode } from 'react'
import { Link } from 'react-router-dom'
import { Footer } from '../../components/Footer'
import { Banner, ErrorNote, Skeleton } from '../../components/States'
import { get } from '../../lib/api'
import type { components } from '../../lib/api-types'

type Legal = components['schemas']['LegalOut']

export const useLegal = () => useQuery({ queryKey: ['legal'], queryFn: () => get<Legal>('/legal'), staleTime: 5 * 60_000 })

const FIELD_RU: Record<string, string> = {
  name: 'Наименование или ФИО оператора', legal_status: 'Организационно-правовая форма', inn: 'ИНН', ogrn: 'ОГРН / ОГРНИП',
  address: 'Адрес для корреспонденции', email: 'Адрес электронной почты для запросов', rkn_notice: 'Номер в реестре операторов Роскомнадзора',
}

/** Значение реквизита либо честная пометка: ничего не подставляется за оператора. */
const val = (v: string | undefined) => (v ? v : <span className="text-risk-medium">не заполнено оператором</span>)

function LegalFrame({ title, children }: { title: string; children: (d: Legal) => ReactNode }) {
  const q = useLegal()
  useEffect(() => { document.title = `${title} — DoorAIn` }, [title])
  return (
    <div className="min-h-dvh bg-page px-4 py-8">
      <article className="legal zone mx-auto max-w-3xl space-y-3 !p-6 sm:!p-8">
        <p className="flex items-center gap-2"><img src="/favicon.svg" alt="" className="size-6" /><Link to="/" className="display-s no-underline text-ink">DoorAIn</Link></p>
        <h1 className="display-m">{title}</h1>
        {q.isLoading && <Skeleton lines={8} />}
        {q.isError && <ErrorNote error={q.error} onRetry={() => q.refetch()} />}
        {q.data && (
          <>
            <p className="caption">Редакция от {q.data.version}</p>
            {q.data.missing.length > 0 && (
              <Banner tone="warn">Реквизиты оператора ещё не заполнены ({q.data.missing.map((k) => FIELD_RU[k]?.toLowerCase() ?? k).join(', ')}). До заполнения документ не готов к публичному запуску; текст подлежит проверке юристом.</Banner>
            )}
            {children(q.data)}
          </>
        )}
      </article>
      <Footer className="mx-auto mt-6 max-w-3xl" />
    </div>
  )
}

function Operator({ d }: { d: Legal }) {
  return (
    <ul>
      {(['name', 'legal_status', 'inn', 'ogrn', 'address', 'email'] as const).map((k) => <li key={k}>{FIELD_RU[k]}: {val(d.operator[k])}</li>)}
      {d.operator['rkn_notice'] && <li>{FIELD_RU['rkn_notice']}: {d.operator['rkn_notice']}</li>}
    </ul>
  )
}

