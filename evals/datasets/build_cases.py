def main() -> None:
    out = Path(__file__).with_name("cases.jsonl")
    rows = []
    for i, (kind, role, q, topics, acts, refuse, hist) in enumerate(CASES, 1):
        cid = f"c{i:03d}"
        rows.append({
            "id": cid, "split": "calibration" if zlib.crc32(cid.encode()) % 2 == 0 else "holdout", "kind": kind, "role": role, "question": q, "history": hist,
            "expected_topics": topics, "expected_acts": acts, "expected_refusal": refuse, "status": "hypothesis", "expert_verified": False,
        })
    out.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n", encoding="utf-8")
    cal = sum(r["split"] == "calibration" for r in rows)
    print(f"{len(rows)} кейсов: calibration={cal}, holdout={len(rows) - cal}, ловушек-отказов={sum(r['expected_refusal'] for r in rows)}")


if __name__ == "__main__":
    main()
